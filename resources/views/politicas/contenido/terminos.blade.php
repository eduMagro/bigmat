<h2 class="text-lg font-bold text-gray-900 mb-4">Terminos y Condiciones de Uso</h2>

<p class="text-gray-600 mb-4"><strong>Ultima actualizacion:</strong> {{ now()->format('d/m/Y') }}</p>

<h3 class="font-semibold text-gray-800 mt-4 mb-2">1. Objeto</h3>
<p class="text-gray-700 mb-3">
    Los presentes Terminos y Condiciones regulan el acceso y uso de la aplicacion de gestion laboral interna de
    <strong>BigMat Los Palacios</strong> (en adelante, "la Aplicacion"), destinada exclusivamente a los
    empleados y personal autorizado de la empresa.
</p>

<h3 class="font-semibold text-gray-800 mt-4 mb-2">2. Acceso a la Aplicacion</h3>
<p class="text-gray-700 mb-3">
    El acceso a la Aplicacion esta restringido a:
</p>
<ul class="list-disc list-inside text-gray-700 mb-3 space-y-1">
    <li>Empleados activos de BigMat Los Palacios</li>
    <li>Personal de administracion y direccion autorizado</li>
    <li>Personal tecnico de mantenimiento del sistema</li>
</ul>
<p class="text-gray-700 mb-3">
    Cada usuario recibira credenciales personales e intransferibles. El uso de credenciales de otro usuario
    esta estrictamente prohibido.
</p>

<h3 class="font-semibold text-gray-800 mt-4 mb-2">3. Funcionalidades</h3>
<p class="text-gray-700 mb-3">
    La Aplicacion permite, entre otras funciones:
</p>
<ul class="list-disc list-inside text-gray-700 mb-3 space-y-1">
    <li>Registro de jornada laboral (fichajes de entrada/salida)</li>
    <li>Consulta de turnos y planificacion</li>
    <li>Solicitud y gestion de vacaciones y permisos</li>
    <li>Comunicacion interna mediante sistema de alertas</li>
    <li>Acceso a documentacion laboral personal</li>
    <li>Consulta de informacion de nominas</li>
</ul>

<h3 class="font-semibold text-gray-800 mt-4 mb-2">4. Obligaciones del Usuario</h3>
<p class="text-gray-700 mb-2">El usuario se compromete a:</p>
<ul class="list-disc list-inside text-gray-700 mb-3 space-y-1">
    <li><strong>Confidencialidad:</strong> Mantener sus credenciales de acceso (usuario y contrasena) en secreto y no compartirlas con terceros</li>
    <li><strong>Uso adecuado:</strong> Utilizar la Aplicacion unicamente para los fines laborales previstos</li>
    <li><strong>Veracidad:</strong> Proporcionar informacion veraz en los registros de jornada y solicitudes</li>
    <li><strong>Fichaje personal:</strong> Realizar los fichajes de forma personal, sin delegar en companeros</li>
    <li><strong>Seguridad:</strong> Cerrar sesion al finalizar el uso de la Aplicacion, especialmente en dispositivos compartidos</li>
    <li><strong>Notificacion:</strong> Comunicar inmediatamente cualquier uso no autorizado de su cuenta o brecha de seguridad</li>
</ul>

<h3 class="font-semibold text-gray-800 mt-4 mb-2">5. Prohibiciones</h3>
<p class="text-gray-700 mb-2">Queda expresamente prohibido:</p>
<ul class="list-disc list-inside text-gray-700 mb-3 space-y-1">
    <li>Ceder o compartir credenciales de acceso</li>
    <li>Fichar en nombre de otro empleado</li>
    <li>Falsear registros de jornada o ubicacion</li>
    <li>Intentar acceder a datos o funciones no autorizadas para su perfil</li>
    <li>Utilizar la Aplicacion para fines distintos a los laborales</li>
    <li>Realizar ingeniera inversa o intentar vulnerar la seguridad del sistema</li>
    <li>Compartir informacion confidencial de la empresa obtenida a traves de la Aplicacion</li>
</ul>

<h3 class="font-semibold text-gray-800 mt-4 mb-2">6. Registro de Jornada y Geolocalizacion</h3>
<p class="text-gray-700 mb-3">
    El registro de jornada laboral es <strong>obligatorio</strong> segun el Real Decreto-ley 8/2019.
    Para verificar que el fichaje se realiza desde el lugar de trabajo, la Aplicacion puede solicitar acceso
    a la ubicacion del dispositivo. Esta informacion se utiliza unicamente para validar el fichaje y
    se trata conforme a nuestra Politica de Privacidad.
</p>

<h3 class="font-semibold text-gray-800 mt-4 mb-2">7. Disponibilidad del Servicio</h3>
<p class="text-gray-700 mb-3">
    BigMat Los Palacios hara esfuerzos razonables para mantener la Aplicacion disponible, pero no garantiza
    su funcionamiento ininterrumpido. Pueden producirse interrupciones por:
</p>
<ul class="list-disc list-inside text-gray-700 mb-3 space-y-1">
    <li>Mantenimiento programado o de emergencia</li>
    <li>Fallos tecnicos o de conectividad</li>
    <li>Causas de fuerza mayor</li>
</ul>
<p class="text-gray-700 mb-3">
    En caso de indisponibilidad prolongada, se habilitaran medios alternativos para el registro de jornada.
</p>

<h3 class="font-semibold text-gray-800 mt-4 mb-2">8. Propiedad Intelectual</h3>
<p class="text-gray-700 mb-3">
    La Aplicacion, incluyendo su codigo, diseno, graficos, textos y demas elementos, es propiedad de
    BigMat Los Palacios o de sus licenciantes. El usuario no adquiere ningún derecho de propiedad
    intelectual por el uso de la Aplicacion.
</p>

<h3 class="font-semibold text-gray-800 mt-4 mb-2">9. Consecuencias del Incumplimiento</h3>
<p class="text-gray-700 mb-3">
    El incumplimiento de estos Terminos y Condiciones podra dar lugar a:
</p>
<ul class="list-disc list-inside text-gray-700 mb-3 space-y-1">
    <li>Suspension temporal del acceso a la Aplicacion</li>
    <li>Revocacion definitiva del acceso</li>
    <li>Medidas disciplinarias conforme al Estatuto de los Trabajadores y convenio colectivo aplicable</li>
    <li>Acciones legales en caso de delitos o infracciones graves</li>
</ul>

